for area,topic,rx in T:
    r=re.compile(rx,re.I); hits={}
    for vid,segs in d.items():
        for ts,tx in segs:
            if r.search(tx):
                hits.setdefault(vid,ts)
    refs=sorted(hits.items(),key=lambda x:lab[x[0]])
    res.append((area,topic,len(refs),[f"{lab[v]}@{t}" for v,t in refs]))
