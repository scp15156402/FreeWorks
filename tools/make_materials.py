def uid(name):
    return str(uuid.uuid5(uuid.NAMESPACE_URL, "https://github.com/scp15156402/FreeWorks/material/" + name))


def card(cat, name, rho, mech, col, desc):
    r, g, b = col
    lines = ["---", "# Generated by tools/make_materials.py - FreeWorks material library",
             "General:",
             '  UUID: "%s"' % uid(name),
             '  Author: "FreeWorks"',
             '  License: "LGPL-2.1-or-later"',
             '  Name: "%s"' % name,
             '  Description: "%s (FreeWorks library, SOLIDWORKS-style name)"' % desc,
             "Models:"]
    if mech:
        e, nu, ys, uts = mech
        lines += ["  LinearElastic:", "    UUID: '%s'" % LINEAR_ELASTIC, '    Density: "%g kg/m^3"' % rho]
        lines.append('    YoungsModulus: "%g GPa"' % e)
        lines.append('    PoissonRatio: "%g"' % nu)
        if ys:
            lines.append('    YieldStrength: "%g MPa"' % ys)
        if uts:
            lines.append('    UltimateTensileStrength: "%g MPa"' % uts)
    else:
        lines += ["  Density:", "    UUID: '%s'" % DENSITY, '    Density: "%g kg/m^3"' % rho]
    lines += ["AppearanceModels:", "  BasicRendering:", "    UUID: '%s'" % BASIC_RENDERING,
              '    AmbientColor: "(%.4f, %.4f, %.4f, 1.0)"' % (r * 0.3, g * 0.3, b * 0.3),
              '    DiffuseColor: "(%.4f, %.4f, %.4f, 1.0)"' % (r, g, b),
              '    EmissiveColor: "(0.0000, 0.0000, 0.0000, 1.0)"',
              '    Shininess: "%s"' % ("0.2000" if cat != "Plastics" else "0.1000"),
              '    SpecularColor: "(0.5000, 0.5000, 0.5000, 1.0)"',
              '    Transparency: "0.0"', ""]
    return "\n".join(lines)


def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    for m in MATERIALS:
        d = os.path.join(OUT, m[0])
        os.makedirs(d, exist_ok=True)
        fn = m[1].replace("/", "-") + ".FCMat"
        with open(os.path.join(d, fn), "w", encoding="utf-8") as f:
            f.write(card(*m))
    print("wrote %d materials to %s" % (len(MATERIALS), OUT))


if __name__ == "__main__":
    main()
